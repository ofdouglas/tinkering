#ifndef MEM_MAP_H
#define MEM_MAP_H

#define ROM_ADDR_MSB 12
#define SRAM_DATA_ADDR_MSB 15
#define SRAM_TEXT_ADDR_MSB 15
#define PERIPH_ADDR_MSB 7

#define ROM_BASE 0x00010000
#define ROM_SIZE 0x00002000
#define ROM_END (ROM_BASE + ROM_SIZE)

#define SRAM_DATA_BASE 0x10000000
#define SRAM_DATA_SIZE 0x00008000
#define SRAM_DATA_END (SRAM_DATA_BASE + SRAM_DATA_SIZE)

#define SRAM_TEXT_BASE 0x10008000
#define SRAM_TEXT_SIZE 0x00008000
#define SRAM_TEXT_END (SRAM_TEXT_BASE + SRAM_TEXT_SIZE)

#define PERIPH_BASE 0x80000000

#define LED_BASE (PERIPH_BASE + 0x00000000)
#define UART_BASE (PERIPH_BASE + 0x00000100)
#define MTIM_BASE (PERIPH_BASE + 0x00000200)

#endif